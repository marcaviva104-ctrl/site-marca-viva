-- Tabela Pai: Protocolos
create table if not exists protocols (
    id text primary key, -- #MV-2026-XXXX
    client_id uuid references auth.users(id),
    column_id bigint default 1,
    total_amount numeric default 0.00,
    paid_amount numeric default 0.00,
    payment_status text default 'pending', -- pending, partial_50, paid_full
    notes text,
    requires_physical_sample boolean default false,
    art_approved boolean default false,
    art_approved_at timestamp with time zone,
    created_at timestamp with time zone default timezone('utc'::text, now()),
    updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- Tabela Filha: Itens do Protocolo
create table if not exists protocol_items (
    id bigint generated by default as identity primary key,
    protocol_id text references protocols(id) on delete cascade,
    product_name text not null,
    quantity integer not null,
    unit_price numeric not null,
    total_price numeric not null,
    customization_details jsonb -- { cor: 'azul', logo: 'url...' }
);

