-- Tabela de Histórico (Auditoria)
create table if not exists protocol_history (
  id bigint generated by default as identity primary key,
  protocol_id text references protocols(id) on delete cascade,
  actor_id uuid references auth.users(id),
  action text not null,
  details jsonb,
  created_at timestamp with time zone default timezone('utc'::text, now())
);

-- Habilitar RLS nas tabelas principais
alter table protocols enable row level security;
alter table protocol_items enable row level security;
alter table protocol_history enable row level security;

-- Política Protocols: Cliente vê seus, Admin vê tudo
create policy "Cliente vê seus protocolos" on protocols
for select using (auth.uid() = client_id);

create policy "Admin vê tudo protocolos" on protocols
for all using (auth.role() = 'authenticated'); -- Simplificado, ideal filtrar por role='admin' na tabela profiles

-- Política Histórico: Igual
create policy "Cliente vê seu histórico" on protocol_history
for select using (
  exists (
    select 1 from protocols p 
    where p.id = protocol_history.protocol_id 
    and p.client_id = auth.uid()
  )
);

create policy "Admin vê tudo histórico" on protocol_history
for select using (auth.role() = 'authenticated');


-- =============================================================================
-- 4. FUNÇÃO SEGURA 
-- =============================================================================

create or replace function move_protocol(
  p_protocol_id text,
  p_new_column_id bigint,
  p_reason text default null
) returns void as $$
declare
  v_old_col bigint;
  v_actor uuid;
begin
  v_actor := auth.uid();
  select column_id into v_old_col from protocols where id = p_protocol_id;

  if v_old_col is null then
    raise exception 'Protocolo não encontrado';
  end if;

  update protocols 
  set column_id = p_new_column_id, 
      updated_at = now()
  where id = p_protocol_id;

  insert into protocol_history (protocol_id, actor_id, action, details)
  values (
    p_protocol_id, 
    v_actor, 
    'MOVED', 
    jsonb_build_object('from', v_old_col, 'to', p_new_column_id, 'reason', p_reason)
  );
end;
$$ language plpgsql security definer;
