-- DESCRIÇÃO: Cria a estrutura para o sistema de Protocolos, Kanban e Flexibilidade Financeira.

-- 1. Tabela de Colunas do Kanban (O "Trello" configurável)
create table kanban_columns (
  id bigint generated by default as identity primary key,
  title text not null, -- Ex: 'Entrada', 'Arte', 'Produção'
  position integer not null, -- Ordem das colunas (1, 2, 3...)
  color text default '#e2e8f0', -- Cor visual da coluna
  is_locked boolean default false -- Se true, usuário não pode deletar
);

-- Insere as colunas padrão
insert into kanban_columns (title, position, color, is_locked) values
